// Текущий язык (по умолчанию русский)
let currentLang = 'en';

// Функция получения перевода для ключа в текущем языке
function t(key) {
    const keys = key.split('.');
    let value = translations[currentLang];
    for (let k of keys) {
        if (value && value[k] !== undefined) {
            value = value[k];
        } else {
            return key; // если перевода нет, возвращаем сам ключ
        }
    }
    return value;
}

// Функция применения переводов ко всем статическим элементам на странице
function applyTranslations() {
    // Меню
    const upEl = document.getElementById('up');
    if (upEl) upEl.textContent = t('menuUp');
    const contactsEl = document.getElementById('contacts');
    if (contactsEl) contactsEl.textContent = t('menuContacts');

    // Hero
    const heroTitle = document.querySelector('.hero__title');
    if (heroTitle) heroTitle.innerHTML = t('heroTitle'); // используем innerHTML для поддержки <br>
    const heroSubtitle = document.querySelector('.hero__subtitle');
    if (heroSubtitle) heroSubtitle.textContent = t('heroSubtitle');
    const heroCta = document.querySelector('.hero__cta');
    if (heroCta) heroCta.textContent = t('heroCta');

    // Кнопки "More" в описаниях (все элементы с классом ...__button)
    const moreButtons = document.querySelectorAll('[class^="showcase__description_"][class*="__button"]');
    moreButtons.forEach(btn => {
        btn.textContent = t('moreButton');
    });

    // Метка в селекторе версий
    const versionLabel = document.querySelector('.modal__version-label');
    if (versionLabel) versionLabel.textContent = t('versionLabel');

    // Обновить содержимое модального окна, если оно открыто
    const modal = document.getElementById('demo-modal');
    if (modal && modal.classList.contains('modal--open') && window.currentDetailKey) {
        // Используем глобальную функцию fillModal для перезагрузки текущего товара
        if (typeof window.fillModal === 'function') {
            window.fillModal(window.currentDetailKey);
        }
    }
}

// Функция установки языка
function setLanguage(lang) {
    if (lang === currentLang) return;
    currentLang = lang;
    localStorage.setItem('lang', lang);
    applyTranslations();
    // Обновить также динамический контент модального окна, если открыто
    // (это уже сделано в applyTranslations через проверку)

    // Добавляем/удаляем класс для смены шрифта
    document.body.classList.remove('lang-ru', 'lang-en');
    document.body.classList.add(`lang-${lang}`);
}

// Инициализация языка при загрузке
function initLanguage() {
    const savedLang = localStorage.getItem('lang');
    if (savedLang && translations[savedLang]) {
        currentLang = savedLang;
    } else {
        const browserLang = navigator.language || navigator.userLanguage;
        if (browserLang.startsWith('en')) {
            currentLang = 'en';
        } else {
            currentLang = 'ru';
        }
    }

    document.body.classList.remove('lang-ru', 'lang-en');
    document.body.classList.add(`lang-${currentLang}`);
    applyTranslations();
}

// Экспортируем функции и данные для использования в других скриптах
window.translation = {
    setLanguage,
    getCurrentLang: () => currentLang,
    t,
    translations,
    details: () => translations[currentLang].details
};

// Обработчики для кнопок языка
document.addEventListener('DOMContentLoaded', function() {
    const langButtons = document.querySelectorAll('.lang-btn');
    langButtons.forEach(btn => {
        btn.addEventListener('click', function(e) {
            const lang = this.dataset.lang;
            window.translation.setLanguage(lang);
            langButtons.forEach(b => b.classList.remove('active'));
            this.classList.add('active');
        });
    });
    
    // Установить активную кнопку при загрузке
    const currentLang = window.translation.getCurrentLang();
    const activeBtn = document.querySelector(`.lang-btn[data-lang="${currentLang}"]`);
    if (activeBtn) activeBtn.classList.add('active');

    // Инициализация языка после загрузки DOM
    initLanguage();
});